defmodule AshR2RML.OntologyFirstDomainsTest do
  use ExUnit.Case, async: false

  alias AshR2RML.Ggen

  @fixture Path.expand("fixtures/natfac.profile.ttl", __DIR__)
  @modules [
    NatFac.Facilities,
    NatFac.Facilities.Party,
    NatFac.Facilities.Trade,
    NatFac.Facilities.Site,
    NatFac.Facilities.Client,
    NatFac.Facilities.Provider,
    NatFac.Repo
  ]

  setup_all do
    on_exit(fn ->
      for m <- @modules,
          do:
            (
              :code.purge(m)
              :code.delete(m)
            )
    end)

    {:ok, turtle: File.read!(@fixture)}
  end

  test "per_resource bundle manufactures domain + resources that compile as real Ash", %{turtle: turtle} do
    assert {:ok, bundle} = Ggen.compile_turtle_bundle(turtle, files: :per_resource)
    refute Map.has_key?(bundle.files, "generated/ash/ontology_resources.ex")

    ash_paths = bundle.files |> Map.keys() |> Enum.filter(&String.starts_with?(&1, "generated/ash/")) |> Enum.sort()

    assert ash_paths == [
             "generated/ash/nat_fac/facilities.ex",
             "generated/ash/nat_fac/facilities/client.ex",
             "generated/ash/nat_fac/facilities/party.ex",
             "generated/ash/nat_fac/facilities/provider.ex",
             "generated/ash/nat_fac/facilities/site.ex",
             "generated/ash/nat_fac/facilities/trade.ex"
           ]

    assert Enum.sort(bundle.manufacturing_plan.ordered_paths) == Enum.sort(Map.keys(bundle.files))
    assert Map.has_key?(bundle.files, "receipts/ash-file-set.json")

    for path <- ash_paths do
      assert String.starts_with?(bundle.files[path], "# GENERATED by ash_r2rml — DO NOT EDIT. Source: ")
    end

    Code.compile_string(
      "defmodule NatFac.Repo do\n  use AshPostgres.Repo, otp_app: :ash_r2rml\n  def installed_extensions, do: []\nend"
    )

    # Dependency-safe order: repo, then the domain (resources verify their domain is a Spark DSL
    # module), then resources (belongs_to/has_many destinations resolve lazily).
    Code.compile_string(bundle.files["generated/ash/nat_fac/facilities.ex"])

    for name <- ["party", "trade", "client", "provider", "site"],
        do: Code.compile_string(bundle.files["generated/ash/nat_fac/facilities/#{name}.ex"])

    resources = Ash.Domain.Info.resources(NatFac.Facilities)

    assert Enum.sort(resources) ==
             Enum.sort([
               NatFac.Facilities.Party,
               NatFac.Facilities.Trade,
               NatFac.Facilities.Site,
               NatFac.Facilities.Client,
               NatFac.Facilities.Provider
             ])

    assert Ash.Resource.Info.domain(NatFac.Facilities.Site) == NatFac.Facilities

    has_many = Ash.Resource.Info.relationship(NatFac.Facilities.Client, :sites)
    assert has_many.type == :has_many
    assert has_many.destination == NatFac.Facilities.Site
    assert has_many.destination_attribute == :client_id

    party_rels = NatFac.Facilities.Party |> Ash.Resource.Info.relationships() |> Enum.map(&{&1.name, &1.type})
    assert {:clients, :has_many} in party_rels and {:providers, :has_many} in party_rels
  end

  test "single layout keeps one file and still carries GENERATED headers and domain", %{turtle: turtle} do
    assert {:ok, bundle} = Ggen.compile_turtle_bundle(turtle)
    single = bundle.files["generated/ash/ontology_resources.ex"]
    assert single =~ "domain: NatFac.Facilities,"
    assert single =~ "defmodule NatFac.Facilities do"
    assert length(Regex.scan(~r/^# GENERATED by ash_r2rml/m, single)) == 6
  end

  test "malformed domain module is refused with a typed refusal", %{turtle: turtle} do
    bad =
      String.replace(turtle, ~s(r2ml:domainModule "NatFac.Facilities"), ~s(r2ml:domainModule "not a module"),
        global: false
      )

    assert {:error, refusals} = Ggen.compile_turtle_bundle(bad)
    assert Enum.any?(List.wrap(refusals), &(inspect(&1) =~ "domainModule"))
  end

  test "inverse name colliding with a target attribute is refused", %{turtle: turtle} do
    bad = String.replace(turtle, ~s(r2ml:inverseName "sites"), ~s(r2ml:inverseName "party_id"), global: false)
    assert {:error, refusals} = Ggen.compile_turtle_bundle(bad)
    assert Enum.any?(List.wrap(refusals), &(inspect(&1) =~ "inverseName"))
  end
end
