defmodule AshR2RML.OntologyFirstExtensionsTest do
  @moduledoc """
  L4-L10: enums, tenancy, actions, policies, state machines, UUID ids and the realigned pack
  gates, each proven by compiling the emitted source and introspecting the real Ash modules.
  """
  use ExUnit.Case, async: false

  alias AshR2RML.Ggen

  @prefixes """
  @prefix sh: <http://www.w3.org/ns/shacl#> .
  @prefix xsd: <http://www.w3.org/2001/XMLSchema#> .
  @prefix nf: <https://ext.example/ns#> .
  @prefix r2ml: <https://seanchatmangpt.github.io/ash_r2rml#> .
  """

  @repo "defmodule Ext.Repo do\n  use AshPostgres.Repo, otp_app: :ash_r2rml\n  def installed_extensions, do: [\"ash-functions\"]\n  def min_pg_version, do: %Version{major: 16, minor: 0, patch: 0}\nend"

  # One shape for module `Ext.<name>` in domain `Ext.<name>Dom`. `repo?: false` keeps the resource on
  # the ETS data layer so actions really run.
  defp shape(name, props, extra \\ "", opts \\ []) do
    repo = if Keyword.get(opts, :repo?, true), do: ~s(r2ml:repoModule "Ext.Repo" ;), else: ""

    @prefixes <>
      """
      nf:#{name}Shape a sh:NodeShape ; sh:targetClass nf:#{name} ;
        r2ml:ashModule "Ext.#{name}" ; r2ml:domainModule "Ext.#{name}Dom" ; #{repo} r2ml:tableName "#{String.downcase(name)}s" ;
        r2ml:subjectTemplate "https://ext.example/#{String.downcase(name)}s/{id}" ;
        r2ml:identity [ r2ml:identityName "primary" ; r2ml:identityKey "id" ; r2ml:primaryIdentity true ] ;
        #{extra}
        sh:property [ sh:path nf:id ; r2ml:ashName "id" ; r2ml:ashType "uuid" ; r2ml:generated true ; r2ml:postgresType "UUID" ; sh:datatype xsd:string ; sh:minCount 1 ; sh:maxCount 1 ] ;
        #{props}
        .
      """
  end

  defp str(path, extra \\ "", min \\ 1),
    do:
      ~s(sh:property [ sh:path nf:#{path} ; r2ml:ashName "#{path}" ; r2ml:postgresType "TEXT" ; sh:datatype xsd:string ; sh:minCount #{min} ; sh:maxCount 1 #{extra} ] ;)

  # Compile order: repo/check stubs are the caller's; enums, then domains, then resources.
  defp load!(bundle) do
    texts =
      bundle.files
      |> Enum.filter(fn {path, _} -> String.starts_with?(path, "generated/ash/") end)
      |> Enum.sort()
      |> Enum.map(&elem(&1, 1))

    rank = fn text ->
      cond do
        text =~ "use Ash.Type.Enum" -> 0
        text =~ "use Ash.Domain" -> 1
        true -> 2
      end
    end

    # Other test files emit the same module names; their derived Inspect impls are never purged.
    for {m, _} <- :code.all_loaded(),
        name = Atom.to_string(m),
        String.starts_with?(name, ["Elixir.Inspect.NatFac.", "Elixir.Inspect.Ext."]) do
      :code.purge(m)
      :code.delete(m)
    end

    {enums, rest} = texts |> Enum.sort_by(rank) |> Enum.split_with(&(rank.(&1) == 0))

    # Enums first; domains and resources in ONE compile so Spark verifiers see every module.
    compiled = Enum.flat_map(enums, &Code.compile_string/1) ++ Code.compile_string(Enum.join(rest, "\n"))
    modules = Enum.map(compiled, &elem(&1, 0))

    on_exit(fn ->
      # Ash derives Inspect impls; they are not in the compile result and would otherwise be
      # "redefined" (a warning) by the next test that emits the same module names.
      for m <- modules, m2 <- [m, Module.concat(Inspect, m)] do
        :code.purge(m2)
        :code.delete(m2)
      end
    end)

    modules
  end

  defp repo! do
    unless Code.ensure_loaded?(Ext.Repo), do: Code.compile_string(@repo)
  end

  defp stub!(name) do
    unless Code.ensure_loaded?(Module.concat([name])) do
      Code.compile_string("""
      defmodule #{name} do
        use Ash.Policy.SimpleCheck
        def describe(_), do: "stub #{name}"
        def match?(actor, _context, _opts), do: actor == :allowed
      end
      """)
    end
  end

  setup_all do
    repo!()
    :ok
  end

  describe "L4 enums" do
    test "sh:in emits an Ash.Type.Enum module used by the attribute; storage stays TEXT" do
      ttl = shape("Enum1", str("status", ~s|; sh:in ( "open" "closed" ) |))
      assert {:ok, bundle} = Ggen.compile_turtle_bundle(ttl, files: :per_resource)

      assert Map.has_key?(bundle.files, "generated/ash/ext/enum1/status.ex")
      enum_text = bundle.files["generated/ash/ext/enum1/status.ex"]
      assert String.starts_with?(enum_text, "# GENERATED by ash_r2rml — DO NOT EDIT. Source: ")
      assert enum_text =~ "use Ash.Type.Enum, values: [:open, :closed]"

      load!(bundle)
      attribute = Ash.Resource.Info.attribute(Ext.Enum1, :status)
      assert attribute.type == Ext.Enum1.Status
      assert attribute.type.values() == [:open, :closed]
      assert {:ok, :open} = Ash.Type.cast_input(Ext.Enum1.Status, "open", [])
      assert {:error, _} = Ash.Type.cast_input(Ext.Enum1.Status, "nope", [])

      assert bundle.files["generated/sql/semantic_schema.sql"] =~ ~s("status" TEXT NOT NULL)
      assert bundle.files["generated/shacl/operational-profile.ttl"] =~ ~s|sh:in ( "open" "closed" )|
      assert bundle.files["priv/r2rml/mapping.ttl"] =~ "http://www.w3.org/2001/XMLSchema#string"
    end

    test "single layout inlines the enum module before the resource; r2ml:enumModule overrides the name" do
      ttl = shape("Enum2", str("kind", ~s|; r2ml:enumModule "Ext.Shared.Kind" ; sh:in ( "a" "b" ) |))
      assert {:ok, bundle} = Ggen.compile_turtle_bundle(ttl)
      single = bundle.files["generated/ash/ontology_resources.ex"]
      assert single =~ "defmodule Ext.Shared.Kind do"
      assert :binary.match(single, "defmodule Ext.Shared.Kind") < :binary.match(single, "defmodule Ext.Enum2 do")
    end

    test "non-string and malformed sh:in members are refused" do
      bad = shape("Enum3", str("status", "; sh:in ( 1 2 )"))
      assert {:error, refusals} = Ggen.compile_turtle_bundle(bad)
      assert Enum.any?(List.wrap(refusals), &(inspect(&1) =~ "sh:in"))

      bad2 = shape("Enum3", str("status", ~s|; sh:in ( "has space" ) |))
      assert {:error, _} = Ggen.compile_turtle_bundle(bad2)

      bad3 = shape("Enum3", str("status", ~s|; r2ml:enumModule "not a module" ; sh:in ( "a" ) |))
      assert {:error, refusals} = Ggen.compile_turtle_bundle(bad3)
      assert Enum.any?(List.wrap(refusals), &(inspect(&1) =~ "enumModule"))
    end
  end

  describe "L5 tenancy" do
    @mt ~s(r2ml:multitenancy [ r2ml:tenantStrategy "attribute" ; r2ml:tenantAttribute "org_id" ; r2ml:tenantGlobal false ] ;)

    test "attribute strategy compiles into Ash multitenancy" do
      ttl = shape("Ten1", str("org_id"), @mt)
      assert {:ok, bundle} = Ggen.compile_turtle_bundle(ttl, files: :per_resource)
      load!(bundle)
      assert Ash.Resource.Info.multitenancy_strategy(Ext.Ten1) == :attribute
      assert Ash.Resource.Info.multitenancy_attribute(Ext.Ten1) == :org_id
      assert Ash.Resource.Info.multitenancy_global?(Ext.Ten1) == false
    end

    test "context strategy needs no attribute" do
      ttl = shape("Ten2", "", ~s(r2ml:multitenancy [ r2ml:tenantStrategy "context" ; r2ml:tenantGlobal true ] ;))
      assert {:ok, bundle} = Ggen.compile_turtle_bundle(ttl)
      load!(bundle)
      assert Ash.Resource.Info.multitenancy_strategy(Ext.Ten2) == :context
      assert Ash.Resource.Info.multitenancy_global?(Ext.Ten2) == true
    end

    test "undeclared tenant attribute and unknown strategy are refused" do
      assert {:error, r} = Ggen.compile_turtle_bundle(shape("Ten3", "", @mt))
      assert Enum.any?(List.wrap(r), &(inspect(&1) =~ "tenantAttribute"))

      weird = String.replace(@mt, ~s("attribute" ;), ~s("schema" ;))
      assert {:error, r} = Ggen.compile_turtle_bundle(shape("Ten3", str("org_id"), weird))
      assert Enum.any?(List.wrap(r), &(inspect(&1) =~ "tenantStrategy"))
    end
  end

  describe "L6 actions and policies" do
    @actions """
    r2ml:action [ r2ml:actionName "register" ; r2ml:actionKind "create" ; r2ml:primary true ; r2ml:accept "title" ] ;
    r2ml:action [ r2ml:actionName "find" ; r2ml:actionKind "read" ;
      r2ml:argument [ r2ml:argName "q" ; r2ml:argType "string" ; r2ml:argAllowNil true ] ] ;
    """

    test "declared actions replace their kind in defaults; other kinds stay default" do
      ttl = shape("Act1", str("title"), @actions)
      assert {:ok, bundle} = Ggen.compile_turtle_bundle(ttl, files: :per_resource)
      load!(bundle)

      names = Ext.Act1 |> Ash.Resource.Info.actions() |> Enum.map(&{&1.name, &1.type}) |> Enum.sort()
      assert names == [destroy: :destroy, find: :read, register: :create, update: :update]

      register = Ash.Resource.Info.action(Ext.Act1, :register)
      assert register.accept == [:title]
      assert register.primary?
      find = Ash.Resource.Info.action(Ext.Act1, :find)
      assert [%{name: :q, allow_nil?: true}] = find.arguments
    end

    test "unknown accept attribute and duplicate action names are refused" do
      bad = String.replace(@actions, ~s(r2ml:accept "title"), ~s(r2ml:accept "ghost"))
      assert {:error, r} = Ggen.compile_turtle_bundle(shape("Act2", str("title"), bad))
      assert Enum.any?(List.wrap(r), &(inspect(&1) =~ "accept"))

      dup =
        ~s(r2ml:action [ r2ml:actionName "x" ; r2ml:actionKind "create" ] ; r2ml:action [ r2ml:actionName "x" ; r2ml:actionKind "update" ] ;)

      assert {:error, r} = Ggen.compile_turtle_bundle(shape("Act2", str("title"), dup))
      assert Enum.any?(List.wrap(r), &(inspect(&1) =~ "duplicate"))
    end

    @policies """
    r2ml:policy [ r2ml:policyName "readable" ; r2ml:actionType "read" ; r2ml:forbidIf "Ext.Checks.Banned" ; r2ml:authorizeIf "Ext.Checks.Cap" ; r2ml:bypassActor "Ext.Checks.Root" ] ;
    """

    test "policies emit deny-by-default authorizer, enumerate residue, and enforce at runtime" do
      for m <- ["Ext.Checks.Banned", "Ext.Checks.Cap", "Ext.Checks.Root"], do: stub!(m)

      ttl = shape("Pol1", str("title"), @policies, repo?: false)
      assert {:ok, bundle} = Ggen.compile_turtle_bundle(ttl, files: :per_resource)

      manifest = Jason.decode!(bundle.files["receipts/ash-residue.json"])
      assert manifest["modules"] == ["Ext.Checks.Banned", "Ext.Checks.Cap", "Ext.Checks.Root"]
      assert Enum.all?(manifest["check_modules"], &(&1["resource"] == "Ext.Pol1"))
      assert "receipts/ash-residue.json" in bundle.manufacturing_plan.ordered_paths

      load!(bundle)
      assert Ash.Resource.Info.authorizers(Ext.Pol1) == [Ash.Policy.Authorizer]
      policies = Ash.Policy.Info.policies(Ext.Pol1)
      assert length(policies) == 2

      # Deny-by-default: no policy covers :create, so even an allowed actor cannot create.
      assert Ash.can?({Ext.Pol1, :read}, :allowed)
      refute Ash.can?({Ext.Pol1, :read}, :stranger)
      refute Ash.can?({Ext.Pol1, :create}, :allowed)
    end

    test "check references must be module names, never expressions" do
      bad = String.replace(@policies, ~s("Ext.Checks.Cap"), ~s|"System.halt(1)"|)
      assert {:error, r} = Ggen.compile_turtle_bundle(shape("Pol2", str("title"), bad))
      assert Enum.any?(List.wrap(r), &(inspect(&1) =~ "module-name"))
    end

    test "no residue manifest and unchanged defaults when no policy is declared" do
      assert {:ok, bundle} = Ggen.compile_turtle_bundle(shape("Pol3", str("title")), files: :per_resource)
      refute Map.has_key?(bundle.files, "receipts/ash-residue.json")
      assert bundle.files["generated/ash/ext/pol3.ex"] =~ "defaults [:read, :create, :update, :destroy]"
    end
  end

  describe "L7 state machine" do
    @sm """
    r2ml:stateMachine [ r2ml:stateAttribute "status" ; r2ml:initial "draft" ; r2ml:terminal "done" ;
      r2ml:transition [ r2ml:action "submit" ; r2ml:from "draft" ; r2ml:to "review" ] ;
      r2ml:transition [ r2ml:action "finish" ; r2ml:from "review" ; r2ml:to "done" ] ;
      r2ml:transition [ r2ml:action "finish" ; r2ml:from "draft" ; r2ml:to "done" ] ] ;
    r2ml:action [ r2ml:actionName "open" ; r2ml:actionKind "create" ; r2ml:primary true ; r2ml:accept "title" ] ;
    """

    test "compiles to AshStateMachine, runs transitions, and rejects illegal ones" do
      ttl = shape("Sm1", str("title") <> "\n" <> str("status"), @sm, repo?: false)
      assert {:ok, bundle} = Ggen.compile_turtle_bundle(ttl, files: :per_resource)
      assert bundle.files["generated/ash/ext/sm1/status.ex"] =~ "values: [:draft, :review, :done]"

      load!(bundle)
      assert AshStateMachine in Spark.extensions(Ext.Sm1)
      assert AshStateMachine.Info.state_machine_state_attribute!(Ext.Sm1) == :status
      assert AshStateMachine.Info.state_machine_initial_states!(Ext.Sm1) == [:draft]
      assert AshStateMachine.Info.state_machine_default_initial_state!(Ext.Sm1) == :draft

      transitions =
        Ext.Sm1
        |> AshStateMachine.Info.state_machine_transitions()
        |> Enum.map(&{&1.action, Enum.sort(List.wrap(&1.from)), hd(List.wrap(&1.to))})
        |> Enum.sort()

      assert transitions == [{:finish, [:draft, :review], :done}, {:submit, [:draft], :review}]
      assert Ash.Resource.Info.attribute(Ext.Sm1, :status).type == Ext.Sm1.Status
      assert Ash.Resource.Info.attribute(Ext.Sm1, :status).default == :draft

      record = Ext.Sm1 |> Ash.Changeset.for_create(:open, %{title: "t"}) |> Ash.create!()
      assert record.status == :draft
      record = record |> Ash.Changeset.for_update(:submit, %{}) |> Ash.update!()
      assert record.status == :review
      assert {:error, _} = record |> Ash.Changeset.for_update(:submit, %{}) |> Ash.update()
      record = record |> Ash.Changeset.for_update(:finish, %{}) |> Ash.update!()
      assert record.status == :done
    end

    test "undeclared state in sh:in, dead-end non-terminal, and retargeted action are refused" do
      props = str("title") <> "\n" <> str("status", ~s|; sh:in ( "draft" "review" ) |)
      assert {:error, r} = Ggen.compile_turtle_bundle(shape("Sm2", props, @sm))
      assert Enum.any?(List.wrap(r), &(inspect(&1) =~ "undeclared state"))

      no_terminal = String.replace(@sm, ~s(r2ml:terminal "done" ;), "")
      assert {:error, r} = Ggen.compile_turtle_bundle(shape("Sm2", str("title") <> str("status"), no_terminal))
      assert Enum.any?(List.wrap(r), &(inspect(&1) =~ "dead-end"))

      retarget =
        String.replace(
          @sm,
          ~s(r2ml:action "finish" ; r2ml:from "draft" ; r2ml:to "done"),
          ~s(r2ml:action "finish" ; r2ml:from "draft" ; r2ml:to "review")
        )

      assert {:error, r} = Ggen.compile_turtle_bundle(shape("Sm2", str("title") <> str("status"), retarget))
      assert Enum.any?(List.wrap(r), &(inspect(&1) =~ "different target"))

      missing_attr = String.replace(@sm, ~s(r2ml:stateAttribute "status"), ~s(r2ml:stateAttribute "phase"))
      assert {:error, r} = Ggen.compile_turtle_bundle(shape("Sm2", str("title"), missing_attr))
      assert Enum.any?(List.wrap(r), &(inspect(&1) =~ "stateAttribute"))
    end
  end

  describe "L10 uuid ids" do
    test "r2ml:ashType uuid emits :uuid; r2ml:generated defaults the key to Ash.UUID.generate/0" do
      ttl =
        @prefixes <>
          """
          nf:Uid1Shape a sh:NodeShape ; sh:targetClass nf:Uid1 ;
            r2ml:ashModule "Ext.Uid1" ; r2ml:domainModule "Ext.Uid1Dom" ; r2ml:repoModule "Ext.Repo" ; r2ml:tableName "uid1s" ;
            r2ml:subjectTemplate "https://ext.example/uid1s/{id}" ;
            r2ml:identity [ r2ml:identityName "primary" ; r2ml:identityKey "id" ; r2ml:primaryIdentity true ] ;
            sh:property [ sh:path nf:id ; r2ml:ashName "id" ; r2ml:ashType "uuid" ; r2ml:generated true ; r2ml:postgresType "UUID" ; sh:datatype xsd:string ; sh:minCount 1 ; sh:maxCount 1 ] ;
            sh:property [ sh:path nf:ref ; r2ml:ashName "ref" ; r2ml:ashType "uuid" ; r2ml:postgresType "UUID" ; sh:datatype xsd:string ; sh:minCount 0 ; sh:maxCount 1 ] .
          """

      assert {:ok, bundle} = Ggen.compile_turtle_bundle(ttl, files: :per_resource)
      load!(bundle)
      id = Ash.Resource.Info.attribute(Ext.Uid1, :id)
      assert id.type == Ash.Type.UUID
      assert id.default == (&Ash.UUID.generate/0)
      ref = Ash.Resource.Info.attribute(Ext.Uid1, :ref)
      assert ref.type == Ash.Type.UUID
      assert ref.default == nil
    end

    test "r2ml:generated on a non-key or non-uuid attribute is refused" do
      bad = shape("Uid2", str("title", "; r2ml:generated true"))
      assert {:error, r} = Ggen.compile_turtle_bundle(bad)
      assert Enum.any?(List.wrap(r), &(inspect(&1) =~ "generated"))
    end
  end

  describe "L8 realigned pack gates" do
    @gates Path.expand("../priv/ggen/ash-r2rml-pack/gates", __DIR__)

    defp gate_rows(file, turtle) do
      {:ok, graph} = RDF.Turtle.read_string(turtle)
      query = File.read!(Path.join(@gates, file))
      %SPARQL.Query.Result{results: rows} = SPARQL.execute_query(graph, query)
      rows
    end

    test "gates use the r2ml namespace the ingestion reads" do
      for file <- File.ls!(@gates), String.ends_with?(file, ".rq") do
        text = File.read!(Path.join(@gates, file))
        assert text =~ "https://seanchatmangpt.github.io/ash_r2rml#"
        refute text =~ "ash-r2ml.dev"
      end
    end

    for fixture <- ["natfac.profile.ttl", "natfac_slice1.profile.ttl"] do
      test "both gates are clean on #{fixture}" do
        turtle = File.read!(Path.expand("fixtures/#{unquote(fixture)}", __DIR__))
        assert gate_rows("010_required_resource_contract.rq", turtle) == []
        assert gate_rows("020_property_contract.rq", turtle) == []
      end
    end

    test "gates fire when the contract is broken" do
      turtle = File.read!(Path.expand("fixtures/natfac.profile.ttl", __DIR__))
      broken = String.replace(turtle, ~s(r2ml:tableName "trades" ;), "", global: false)
      rows = gate_rows("010_required_resource_contract.rq", broken)
      assert [row] = rows
      assert row["missing"] |> RDF.Term.value() |> to_string() =~ "tableName"

      broken = String.replace(turtle, ~s(r2ml:sourceKey "client_id" ;), "", global: false)
      assert [_ | _] = gate_rows("020_property_contract.rq", broken)
    end
  end

  describe "NatFac slice-1 fixture" do
    @slice1 Path.expand("fixtures/natfac_slice1.profile.ttl", __DIR__)

    test "full bundle compiles as real Ash and introspects as declared" do
      for m <- ["NatFac.Checks.ActorHasCapability", "NatFac.Checks.ActorIsSystem"], do: stub!(m)
      Code.compile_string(String.replace(@repo, "Ext.Repo", "NatFac.Repo"))

      assert {:ok, bundle} = Ggen.compile_turtle_bundle(File.read!(@slice1), files: :per_resource)
      assert Map.has_key?(bundle.files, "receipts/ash-residue.json")

      residue = Jason.decode!(bundle.files["receipts/ash-residue.json"])
      assert residue["modules"] == ["NatFac.Checks.ActorHasCapability", "NatFac.Checks.ActorIsSystem"]

      modules = load!(bundle)

      for m <- [NatFac.Repo, NatFac.Checks.ActorHasCapability, NatFac.Checks.ActorIsSystem] do
        on_exit(fn ->
          :code.purge(m)
          :code.delete(m)
        end)
      end

      # enums
      enums = [
        {NatFac.Facilities.Provider, :status, [:draft, :under_review, :approved, :suspended, :terminated]},
        {NatFac.Facilities.Provider, :classification, [:national, :regional, :local]},
        {NatFac.Facilities.Client, :client_type, [:direct, :reseller]},
        {NatFac.Facilities.AlignmentTemplate, :tier, [:standard, :preferred, :strategic]},
        {NatFac.Facilities.AlignmentLine, :effect, [:include, :exclude]},
        {NatFac.Facilities.AlignmentLine, :dimension, [:state, :zip, :trade, :segment]}
      ]

      for {resource, attr, values} <- enums do
        type = Ash.Resource.Info.attribute(resource, attr).type
        assert type == Module.concat(resource, Macro.camelize(Atom.to_string(attr)))
        assert type.values() == values
      end

      # tenancy
      for r <- [Client, Brand, Site] do
        mod = Module.concat(NatFac.Facilities, r)
        assert Ash.Resource.Info.multitenancy_strategy(mod) == :attribute
        assert Ash.Resource.Info.multitenancy_attribute(mod) == :operating_dba_id
        assert Ash.Resource.Info.multitenancy_global?(mod) == false
      end

      assert Ash.Resource.Info.multitenancy_strategy(NatFac.Facilities.Provider) == nil

      # actions
      provider_actions = NatFac.Facilities.Provider |> Ash.Resource.Info.actions() |> Enum.map(& &1.name)

      for a <- [:register, :amend, :list, :search, :submit, :approve, :suspend, :reinstate, :terminate, :destroy],
          do: assert(a in provider_actions)

      refute :create in provider_actions
      line_actions = NatFac.Facilities.AlignmentLine |> Ash.Resource.Info.actions() |> Enum.map(& &1.name)
      for a <- [:add, :reorder, :list, :destroy], do: assert(a in line_actions)

      # state machine
      assert AshStateMachine.Info.state_machine_initial_states!(NatFac.Facilities.Provider) == [:draft]

      assert Enum.sort(AshStateMachine.Info.state_machine_all_states(NatFac.Facilities.Provider)) ==
               Enum.sort([:draft, :under_review, :approved, :suspended, :terminated])

      terminate =
        NatFac.Facilities.Provider
        |> AshStateMachine.Info.state_machine_transitions()
        |> Enum.find(&(&1.action == :terminate))

      assert Enum.sort(List.wrap(terminate.from)) == [:approved, :suspended]
      assert List.wrap(terminate.to) == [:terminated]

      # policies
      assert Ash.Resource.Info.authorizers(NatFac.Facilities.Provider) == [Ash.Policy.Authorizer]
      assert length(Ash.Policy.Info.policies(NatFac.Facilities.Provider)) == 5

      assert NatFac.Facilities in modules
      assert length(Ash.Domain.Info.resources(NatFac.Facilities)) == 13
    end

    test "repo-backed emitted source compiles with zero compiler warnings" do
      Code.compile_string(String.replace(@repo, "Ext.Repo", "NatFac.RepoWarn"))
      on_exit(fn -> :code.purge(NatFac.RepoWarn) && :code.delete(NatFac.RepoWarn) end)

      for m <- ["NatFac.Checks.ActorHasCapability", "NatFac.Checks.ActorIsSystem"], do: stub!(m)

      source = File.read!(@slice1) |> String.replace("NatFac.Repo", "NatFac.RepoWarn")
      assert {:ok, bundle} = Ggen.compile_turtle_bundle(source, files: :per_resource)

      stderr = ExUnit.CaptureIO.capture_io(:stderr, fn -> load!(bundle) end)
      assert stderr == ""
    end
  end
